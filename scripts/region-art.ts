// Builds src/regionArt.ts: a small, simplified silhouette of each region for the home cards.
// Run with: npx tsx scripts/region-art.ts
import { writeFileSync, readFileSync } from 'node:fs';
import { geoMercator, geoNaturalEarth1, geoPath } from 'd3-geo';
import { merge, feature } from 'topojson-client';
import { presimplify, simplify, quantile} from 'topojson-simplify';
import { REGIONS, SHAPE_TO_COUNTRY, COUNTRY_BY_ID } from '../src/countries';

const thin = (t: any, q: number) => {
  const p = presimplify(t);
  return simplify(p, quantile(p, q));
};
const topo = thin(JSON.parse(readFileSync('node_modules/world-atlas/countries-110m.json', 'utf8')), 0.5);
const W = 120, H = 80;
const round = (d: string) => d.replace(/\d+\.\d+/g, (n) => String(Math.round(+n * 10) / 10));
const out: Record<string, { w: number; h: number; d: string }> = {};

for (const r of REGIONS) {
  const geoms = topo.objects.countries.geometries.filter((g: any) => {
    const id = SHAPE_TO_COUNTRY.get(g.properties.name);
    return id && COUNTRY_BY_ID.get(id)!.region === r.id;
  });
  const shape = merge(topo, geoms);
  const [w, s, e, n] = r.bbox;
  const pts: [number, number][] = [];
  for (let i = 0; i <= 4; i++) { const lon = w + ((e - w) * i) / 4; pts.push([lon, s], [lon, n]); }
  const proj = geoMercator().rotate([-(w + e) / 2, 0]).fitExtent([[0, 0], [W, H]], { type: 'MultiPoint', coordinates: pts } as any);
  // Shrink the box to what the region actually fills, then clip to it.
  const b = geoPath(proj).bounds(shape);
  const x0 = Math.max(0, b[0][0]), y0 = Math.max(0, b[0][1]), x1 = Math.min(W, b[1][0]), y1 = Math.min(H, b[1][1]);
  proj.translate([proj.translate()[0] - x0, proj.translate()[1] - y0]).clipExtent([[0, 0], [x1 - x0, y1 - y0]]);
  out[r.id] = { w: Math.round(x1 - x0), h: Math.round(y1 - y0), d: round(geoPath(proj).digits(0)(shape)!) };
}
// World: every country merged (no Antarctica), small islands dropped so the drawing stays light.
const all = merge(topo, topo.objects.countries.geometries.filter((g: any) => g.properties.name !== 'Antarctica')) as any;
const world = geoNaturalEarth1().rotate([-10, 0]).fitSize([200, 100], all);
const keep = { type: 'MultiPolygon', coordinates: all.coordinates.filter((c: any) => geoPath(world).area({ type: 'Polygon', coordinates: c } as any) > 4) } as any;
world.fitSize([200, 100], keep);
const wb = geoPath(world).bounds(keep);
world.translate([world.translate()[0] - wb[0][0], world.translate()[1] - wb[0][1]]);
out.world = { w: Math.round(wb[1][0] - wb[0][0]), h: Math.round(wb[1][1] - wb[0][1]), d: geoPath(world).digits(0)(keep)! };

writeFileSync('src/regionArt.ts', `// Generated by scripts/region-art.ts. Simplified region silhouettes for the home cards.\nexport const REGION_ART: Record<string, { w: number; h: number; d: string }> = ${JSON.stringify(out, null, 1)};\n`);
for (const [k, v] of Object.entries(out)) console.log(k, v.w, v.h, v.d.length);
